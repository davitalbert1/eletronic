// Lexer
std::vector<Token> CircuitLanguageParser::tokenize(const std::string& source) {
    std::vector<Token> tokens;
    size_t pos = 0;
    int line = 1;
    int column = 1;

    auto advance = [&]() {
        if (pos < source.size()) {
            if (source[pos] == '\n') {
                line++;
                column = 1;
            } else {
                column++;
            }
            pos++;
        }
    };

    auto peek = [&]() -> char {
        return pos < source.size() ? source[pos] : '\0';
    };
    auto peekNext = [&]() -> char {
        return (pos + 1) < source.size() ? source[pos + 1] : '\0';
    };

    while (pos < source.size()) {
        while (pos < source.size() && std::isspace(source[pos])) advance();
        if (pos >= source.size()) break;

        int tokenLine = line;
        int tokenCol = column;
        char c = source[pos];

        // Comments
        if (c == '/' && peekNext() == '/') {
            while (pos < source.size() && source[pos] != '\n') advance();
            continue;
        }
        if (c == '/' && peekNext() == '*') {
            advance();
            advance();
            while (pos < source.size() && !(source[pos] == '*' && peekNext() == '/')) advance();
            if (pos < source.size()) {
                advance();
                advance();
            }
            continue;
        }

        // Strings
        if (c == '"') {
            advance();
            std::string strVal;
            while (pos < source.size() && source[pos] != '"') {
                if (source[pos] == '\\' && pos + 1 < source.size()) {
                    advance();
                    char esc = source[pos];
                    if (esc == 'n') strVal += '\n';
                    else if (esc == 't') strVal += '\t';
                    else if (esc == '"') strVal += '"';
                    else if (esc == '\\') strVal += '\\';
                    else strVal += esc;
                } else {
                    strVal += source[pos];
                }
                advance();
            }
            if (pos < source.size() && source[pos] == '"') {
                advance();
            }
            tokens.emplace_back(CircuitTokenType::STRING, strVal, tokenLine, tokenCol);
            continue;
        }

        // Single character tokens
        switch (c) {
            case '(':
                tokens.emplace_back(CircuitTokenType::LPAREN, "(", tokenLine, tokenCol);
                advance();
                continue;
            case ')':
                tokens.emplace_back(CircuitTokenType::RPAREN, ")", tokenLine, tokenCol);
                advance();
                continue;
            case '{':
                tokens.emplace_back(CircuitTokenType::LBRACE, "{", tokenLine, tokenCol);
                advance();
                continue;
            case '}':
                tokens.emplace_back(CircuitTokenType::RBRACE, "}", tokenLine, tokenCol);
                advance();
                continue;
            case ',':
                tokens.emplace_back(CircuitTokenType::COMMA, ",", tokenLine, tokenCol);
                advance();
                continue;
            case ':':
                tokens.emplace_back(CircuitTokenType::COLON, ":", tokenLine, tokenCol);
                advance();
                continue;
            case ';':
                tokens.emplace_back(CircuitTokenType::SEMICOLON, ";", tokenLine, tokenCol);
                advance();
                continue;
            case '.':
                tokens.emplace_back(CircuitTokenType::DOT, ".", tokenLine, tokenCol);
                advance();
                continue;
            case '=':
                tokens.emplace_back(CircuitTokenType::EQUALS, "=", tokenLine, tokenCol);
                advance();
                continue;
            case '-':
                if (peekNext() == '>') {
                    advance();
                    advance();
                    tokens.emplace_back(CircuitTokenType::ARROW, "->", tokenLine, tokenCol);
                    continue;
                }
                break;
        }

        // Numbers
        if (std::isdigit(static_cast<unsigned char>(c)) || (c == '-' && std::isdigit(static_cast<unsigned char>(peekNext())))) {
            std::string num;
            if (c == '-') {
                num += c;
                advance();
            }
            while (pos < source.size() && std::isdigit(static_cast<unsigned char>(source[pos]))) {
                num += source[pos];
                advance();
            }
            if (pos < source.size() && source[pos] == '.' && (pos + 1 < source.size() && std::isdigit(static_cast<unsigned char>(source[pos + 1])))) {
                num += source[pos];
                advance();
                while (pos < source.size() && std::isdigit(static_cast<unsigned char>(source[pos]))) {
                    num += source[pos];
                    advance();
                }
            }
            tokens.emplace_back(CircuitTokenType::NUMBER, num, tokenLine, tokenCol);
            continue;
        }

        // Identifiers and keywords
        if (std::isalpha(static_cast<unsigned char>(c)) || c == '_') {
            std::string ident;
            while (pos < source.size() && (std::isalnum(static_cast<unsigned char>(source[pos])) || source[pos] == '_')) {
                ident += source[pos];
                advance();
            }
            static const std::map<std::string, CircuitTokenType> keywords = {
                {"circuit", CircuitTokenType::CIRCUIT}, {"gate", CircuitTokenType::GATE},
                {"wire", CircuitTokenType::WIRE}, {"input", CircuitTokenType::INPUT},
                {"output", CircuitTokenType::OUTPUT}, {"chip", CircuitTokenType::CHIP},
                {"param", CircuitTokenType::PARAM}, {"group", CircuitTokenType::GROUP},
                {"at", CircuitTokenType::AT}
            };
            auto it = keywords.find(ident);
            if (it != keywords.end()) {
                tokens.emplace_back(it->second, ident, tokenLine, tokenCol);
            } else {
                tokens.emplace_back(CircuitTokenType::IDENTIFIER, ident, tokenLine, tokenCol);
            }
            continue;
        }

        // Skip unrecognized characters
        advance();
    }

    tokens.emplace_back(CircuitTokenType::END_OF_FILE, "", line, column);
    return tokens;
}

// Parser
std::shared_ptr<CircuitNode> CircuitLanguageParser::parseCircuit() {
    if (!match(CircuitTokenType::CIRCUIT)) {
        error("Expected 'circuit' keyword");
        return nullptr;
    }
    auto node = std::make_shared<CircuitNode>();
    node->line = current().line;
    if (!match(CircuitTokenType::IDENTIFIER)) {
        error("Expected circuit name");
        return nullptr;
    }
    node->name = previous().value;
    if (check(CircuitTokenType::STRING)) {
        advance();
        node->description = previous().value;
    }
    if (!match(CircuitTokenType::LBRACE)) {
        error("Expected '{' after circuit name");
        return nullptr;
    }
    while (!check(CircuitTokenType::RBRACE) && !isAtEnd()) {
        auto stmt = parseStatement();
        if (stmt) node->children.push_back(stmt);
    }
    if (!match(CircuitTokenType::RBRACE)) {
        error("Expected '}' at end of circuit");
        return nullptr;
    }
    return node;
}

std::shared_ptr<ASTNode> CircuitLanguageParser::parseStatement() {
    if (check(CircuitTokenType::GATE)) return parseGate();
    if (check(CircuitTokenType::WIRE)) return parseWire();
    if (check(CircuitTokenType::INPUT)) return parseInput();
    if (check(CircuitTokenType::OUTPUT)) return parseOutput();
    if (check(CircuitTokenType::CHIP)) return parseChip();
    if (check(CircuitTokenType::GROUP)) return parseGroup();
    error("Unexpected token: " + current().value);
    advance();
    return nullptr;
}

std::shared_ptr<GateNode> CircuitLanguageParser::parseGate() {
    advance();
    auto node = std::make_shared<GateNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected gate type");
        return nullptr;
    }
    node->gateType = current().value;
    advance();
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected gate identifier");
        return nullptr;
    }
    node->id = current().value;
    advance();
    auto pos = parsePosition();
    node->x = pos.x;
    node->y = pos.y;
    if (check(CircuitTokenType::LBRACE)) {
        advance();
        parseParams(node->params);
        if (!match(CircuitTokenType::RBRACE)) error("Expected '}' after parameters");
    }
    return node;
}

std::shared_ptr<WireNode> CircuitLanguageParser::parseWire() {
    advance();
    auto node = std::make_shared<WireNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected source gate identifier");
        return nullptr;
    }
    node->fromGate = current().value;
    advance();
    if (match(CircuitTokenType::DOT)) {
        if (!check(CircuitTokenType::NUMBER)) {
            error("Expected pin number after '.'");
            return nullptr;
        }
        node->fromPin = std::stoi(current().value);
        advance();
    }
    if (!match(CircuitTokenType::ARROW)) {
        error("Expected '->' in wire definition");
        return nullptr;
    }
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected destination gate identifier");
        return nullptr;
    }
    node->toGate = current().value;
    advance();
    if (match(CircuitTokenType::DOT)) {
        if (!check(CircuitTokenType::NUMBER)) {
            error("Expected pin number after '.'");
            return nullptr;
        }
        node->toPin = std::stoi(current().value);
        advance();
    }
    return node;
}

std::shared_ptr<InputNode> CircuitLanguageParser::parseInput() {
    advance();
    auto node = std::make_shared<InputNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected input identifier");
        return nullptr;
    }
    node->id = current().value;
    advance();
    auto pos = parsePosition();
    node->x = pos.x;
    node->y = pos.y;
    return node;
}

std::shared_ptr<OutputNode> CircuitLanguageParser::parseOutput() {
    advance();
    auto node = std::make_shared<OutputNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected output identifier");
        return nullptr;
    }
    node->id = current().value;
    advance();
    auto pos = parsePosition();
    node->x = pos.x;
    node->y = pos.y;
    return node;
}

sf::Vector2f CircuitLanguageParser::parsePosition() {
    sf::Vector2f pos(0, 0);
    if (!match(CircuitTokenType::AT)) {
        error("Expected 'at' keyword before position");
        return pos;
    }
    if (!match(CircuitTokenType::LPAREN)) {
        error("Expected '(' before coordinates");
        return pos;
    }
    if (!check(CircuitTokenType::NUMBER)) {
        error("Expected x coordinate");
        return pos;
    }
    pos.x = std::stof(current().value);
    advance();
    if (!match(CircuitTokenType::COMMA)) {
        error("Expected ',' between coordinates");
        return pos;
    }
    if (!check(CircuitTokenType::NUMBER)) {
        error("Expected y coordinate");
        return pos;
    }
    pos.y = std::stof(current().value);
    advance();
    if (!match(CircuitTokenType::RPAREN)) error("Expected ')' after coordinates");
    return pos;
}

void CircuitLanguageParser::parseParams(std::map<std::string, std::string>& params) {
    while (!check(CircuitTokenType::RBRACE) && !isAtEnd()) {
        if (!check(CircuitTokenType::IDENTIFIER)) break;
        std::string key = current().value;
        advance();
        if (!match(CircuitTokenType::EQUALS)) {
            error("Expected '=' in parameter");
            return;
        }
        std::string value;
        if (check(CircuitTokenType::NUMBER) || check(CircuitTokenType::IDENTIFIER) || check(CircuitTokenType::STRING)) {
            value = current().value;
            advance();
        } else {
            error("Expected value after '='");
            return;
        }
        params[key] = value;
        if (check(CircuitTokenType::COMMA)) advance();
    }
}

bool CircuitLanguageParser::generateCircuit(
    const std::shared_ptr<CircuitNode>& ast,
    CircuitParseResult& result,
    const sf::Font& font) {
    result.circuitName = ast->name;
    result.circuitDescription = ast->description;
    gateMap_.clear();
    for (const auto& child : ast->children) {
        if (auto gateNode = std::dynamic_pointer_cast<GateNode>(child)) {
            sf::Vector2f pos(gateNode->x, gateNode->y);
            auto gate = GateRegistry::instance().createGate(gateNode->gateType, pos, font);
            if (!gate) {
                warning("Unknown gate type: " + gateNode->gateType);
                continue;
            }
            result.gates.push_back(gate);
            gateMap_[gateNode->id] = gate;
        } else if (auto inputNode = std::dynamic_pointer_cast<InputNode>(child)) {
            auto gate = std::make_shared<InputPin>(sf::Vector2f(inputNode->x, inputNode->y), font, inputNode->id);
            result.gates.push_back(gate);
            gateMap_[inputNode->id] = gate;
        } else if (auto outputNode = std::dynamic_pointer_cast<OutputNode>(child)) {
            auto gate = std::make_shared<OutputPin>(sf::Vector2f(outputNode->x, outputNode->y), font, outputNode->id);
            result.gates.push_back(gate);
            gateMap_[outputNode->id] = gate;
        } else if (auto chipNode = std::dynamic_pointer_cast<ChipNode>(child)) {
            auto gate = chip::createChipInstance(chipNode->chipId, sf::Vector2f(chipNode->x, chipNode->y), font);
            if (gate) {
                result.gates.push_back(gate);
                gateMap_[chipNode->instanceId] = gate;
            } else {
                warning("Chip not found: " + chipNode->chipId);
            }
        }
    }
    for (const auto& child : ast->children) {
        if (auto wireNode = std::dynamic_pointer_cast<WireNode>(child)) {
            auto fromIt = gateMap_.find(wireNode->fromGate);
            auto toIt = gateMap_.find(wireNode->toGate);
            if (fromIt == gateMap_.end()) {
                warning("Source gate not found: " + wireNode->fromGate);
                continue;
            }
            if (toIt == gateMap_.end()) {
                warning("Dest gate not found: " + wireNode->toGate);
                continue;
            }
            auto fromGate = fromIt->second;
            auto toGate = toIt->second;
            if (wireNode->fromPin >= 0 && wireNode->fromPin < static_cast<int>(fromGate->outputs.size()) &&
                wireNode->toPin >= 0 && wireNode->toPin < static_cast<int>(toGate->inputs.size())) {
                result.wires.push_back(Wire(&fromGate->outputs[wireNode->fromPin], &toGate->inputs[wireNode->toPin]));
            } else {
                std::string errDetail = "Invalid pin indices for wire: " + wireNode->fromGate + "." + std::to_string(wireNode->fromPin) + 
                    " (outputs: " + std::to_string(fromGate->outputs.size()) + ") -> " + 
                    wireNode->toGate + "." + std::to_string(wireNode->toPin) + 
                    " (inputs: " + std::to_string(toGate->inputs.size()) + ")";
                warning(errDetail);
            }
        }
    }
    result.success = true;
    return result.success;
}

GateType CircuitLanguageParser::mapGateType(const std::string& typeName, std::string& outLabel) {
    GateType t = GateRegistry::instance().stringToType(typeName);
    outLabel = GateRegistry::instance().getCodeName(t);
    return t;
}

bool CircuitLanguageParser::match(CircuitTokenType type) {
    if (check(type)) {
        advance();
        return true;
    }
    return false;
}

bool CircuitLanguageParser::check(CircuitTokenType type) const {
    if (isAtEnd()) return false;
    return current().type == type;
}

const Token& CircuitLanguageParser::current() const {
    return tokens_[currentToken_];
}
const Token& CircuitLanguageParser::previous() const {
    return tokens_[currentToken_ - 1];
}
bool CircuitLanguageParser::isAtEnd() const {
    return current().type == CircuitTokenType::END_OF_FILE;
}

void CircuitLanguageParser::advance() {
    if (!isAtEnd()) currentToken_++;
}

void CircuitLanguageParser::error(const std::string& message) {
    const Token& tok = current();
    errors_.push_back("Line " + std::to_string(tok.line) + ":" + std::to_string(tok.column) + " - " + message);
}

void CircuitLanguageParser::warning(const std::string& message) {
    const Token& tok = current();
    warnings_.push_back("Line " + std::to_string(tok.line) + ":" + std::to_string(tok.column) + " - " + message);
}

std::shared_ptr<ChipNode> CircuitLanguageParser::parseChip() {
    advance();
    auto node = std::make_shared<ChipNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected chip identifier");
        return nullptr;
    }
    node->chipId = current().value;
    advance();
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected instance identifier");
        return nullptr;
    }
    node->instanceId = current().value;
    advance();
    auto pos = parsePosition();
    node->x = pos.x;
    node->y = pos.y;
    return node;
}

std::shared_ptr<GroupNode> CircuitLanguageParser::parseGroup() {
    advance();
    auto node = std::make_shared<GroupNode>();
    node->line = previous().line;
    if (!check(CircuitTokenType::IDENTIFIER)) {
        error("Expected group name");
        return nullptr;
    }
    node->name = current().value;
    advance();
    if (!match(CircuitTokenType::LBRACE)) {
        error("Expected '{' after group name");
        return nullptr;
    }
    while (!check(CircuitTokenType::RBRACE) && !isAtEnd()) {
        auto child = parseStatement();
        if (child) node->children.push_back(child);
    }
    if (!match(CircuitTokenType::RBRACE)) {
        error("Expected '}' at end of group");
        return nullptr;
    }
    return node;
}

std::string CircuitLanguageParser::generateComponentDescription(
    const std::shared_ptr<Gate>& gate,
    const std::vector<std::shared_ptr<Gate>>& allGates,
    const std::vector<Wire>& allWires,
    const std::string& preferredId) {
    if (!gate) return "";

    std::map<Gate*, std::string> gateIds;
    int inputCount = 0, outputCount = 0, gateCount = 0, chipCount = 0;
    for (const auto& g : allGates) {
        if (!g) continue;
        if (g == gate && !preferredId.empty()) {
            gateIds[g.get()] = preferredId;
            continue;
        }
        std::string id;
        switch (g->getType()) {
            case GateType::INPUT_PIN:
                id = "input_" + std::to_string(inputCount++);
                break;
            case GateType::OUTPUT_PIN:
                id = "output_" + std::to_string(outputCount++);
                break;
            case GateType::CHIP:
                id = "chip_" + std::to_string(chipCount++);
                break;
            default:
                id = "gate_" + std::to_string(gateCount++);
                break;
        }
        gateIds[g.get()] = id;
    }

    std::string myId = gateIds[gate.get()];
    if (myId.empty()) myId = preferredId.empty() ? "comp_1" : preferredId;

    std::ostringstream out;
    sf::Vector2f pos = gate->getPosition();

    switch (gate->getType()) {
        case GateType::INPUT_PIN:
            out << "input " << myId << " at (" << pos.x << ", " << pos.y << ")\n";
            break;
        case GateType::OUTPUT_PIN:
            out << "output " << myId << " at (" << pos.x << ", " << pos.y << ")\n";
            break;
        case GateType::CHIP:
            out << "chip " << gate->getChipId() << " " << myId << " at (" << pos.x << ", " << pos.y << ")\n";
            break;
        default: {
            std::string typeName = GateRegistry::instance().getCodeName(gate->getType());
            out << "gate " << typeName << " " << myId << " at (" << pos.x << ", " << pos.y << ")\n";
            break;
        }
    }

    // Wires connected to this gate
    for (const auto& wire : allWires) {
        if (!wire.fromPin || !wire.toPin || !wire.fromPin->parent || !wire.toPin->parent) continue;
        if (wire.fromPin->parent == gate.get() || wire.toPin->parent == gate.get()) {
            auto fromIt = gateIds.find(wire.fromPin->parent);
            auto toIt = gateIds.find(wire.toPin->parent);
            if (fromIt == gateIds.end() || toIt == gateIds.end()) continue;

            int fromPinIdx = -1, toPinIdx = -1;
            for (size_t i = 0; i < wire.fromPin->parent->outputs.size(); i++) {
                if (&wire.fromPin->parent->outputs[i] == wire.fromPin) {
                    fromPinIdx = (int)i;
                    break;
                }
            }
            for (size_t i = 0; i < wire.toPin->parent->inputs.size(); i++) {
                if (&wire.toPin->parent->inputs[i] == wire.toPin) {
                    toPinIdx = (int)i;
                    break;
                }
            }
            if (fromPinIdx >= 0 && toPinIdx >= 0) {
                out << "wire " << fromIt->second << "." << fromPinIdx << " -> " << toIt->second << "." << toPinIdx << "\n";
            }
        }
    }

    return out.str();
}

bool CircuitLanguageParser::applyTextToCircuit(
    const std::string& source,
    std::vector<std::shared_ptr<Gate>>& gates,
    std::vector<Wire>& wires,
    const sf::Font& font,
    std::string& errorMessage,
    std::vector<std::string>& warnings) {

    // First attempt full parse
    auto fullResult = parse(source, font);
    if (fullResult.success) {
        gates = fullResult.gates;
        wires = fullResult.wires;
        warnings = fullResult.warnings;
        return true;
    }

    // If failed, wrap in anonymous circuit block and retry
    std::string wrapped = "circuit AutoCircuit {\n" + source + "\n}\n";
    auto wrappedResult = parse(wrapped, font);
    if (wrappedResult.success) {
        gates = wrappedResult.gates;
        wires = wrappedResult.wires;
        warnings = wrappedResult.warnings;
        return true;
    }

    errorMessage = fullResult.errorMessage.empty() ? wrappedResult.errorMessage : fullResult.errorMessage;
    warnings = fullResult.warnings;
    return false;
}
