// Public Interface
CircuitParseResult CircuitLanguageParser::parse(const std::string& source, const sf::Font& font) {
    CircuitParseResult result;
    source_ = source;
    errors_.clear();
    warnings_.clear();
    gateMap_.clear();
    currentToken_ = 0;

    tokens_ = tokenize(source);
    if (tokens_.empty()) {
        result.errorMessage = "Empty source or tokenization failed";
        return result;
    }

    auto ast = parseCircuit();
    if (!ast) {
        result.errorMessage = errors_.empty() ? "Failed to parse circuit" : errors_[0];
        return result;
    }

    if (!generateCircuit(ast, result, font)) {
        result.errorMessage = errors_.empty() ? "Failed to generate circuit" : errors_[0];
        return result;
    }

    result.success = true;
    result.warnings = warnings_;
    return result;
}

CircuitParseResult CircuitLanguageParser::parseFromFile(const std::string& filePath, const sf::Font& font) {
    CircuitParseResult result;

    std::ifstream file(filePath);
    if (!file.is_open()) {
        result.errorMessage = "Cannot open file: " + filePath;
        return result;
    }

    std::stringstream buffer;
    buffer << file.rdbuf();
    file.close();

    return parse(buffer.str(), font);
}

std::string CircuitLanguageParser::generateDescription(
    const std::vector<std::shared_ptr<Gate>>& gates,
    const std::vector<Wire>& wires,
    const std::string& circuitName,
    const std::string& description) {
    std::ostringstream out;
    out << "// Circuit Description File\n";
    out << "// Generated by Eletronic Simulator\n\n";
    out << "circuit " << circuitName;
    if (!description.empty()) out << " \"" << description << "\"";
    out << "\n{\n\n";

    std::map<Gate*, std::string> gateIds;
    int inputCount = 0, outputCount = 0, gateCount = 0, chipCount = 0;

    for (const auto& gate : gates) {
        std::string id;
        switch (gate->getType()) {
            case GateType::INPUT_PIN:
                id = "input_" + std::to_string(inputCount++);
                break;
            case GateType::OUTPUT_PIN:
                id = "output_" + std::to_string(outputCount++);
                break;
            case GateType::CHIP:
                id = "chip_" + std::to_string(chipCount++);
                break;
            default: id = "gate_" + std::to_string(gateCount++);
            break;
        }
        gateIds[gate.get()] = id;
    }

    for (const auto& gate : gates) {
        auto it = gateIds.find(gate.get());
        if (it == gateIds.end()) continue;
        const std::string& id = it->second;
        sf::Vector2f pos = gate->getPosition();
        switch (gate->getType()) {
            case GateType::INPUT_PIN:
                out << "  input " << id << " at (" << pos.x << ", " << pos.y << ")\n";
                break;
            case GateType::OUTPUT_PIN:
                out << "  output " << id << " at (" << pos.x << ", " << pos.y << ")\n";
                break;
            case GateType::CHIP:
                out << "  chip " << gate->getChipId() << " " << id << " at (" << pos.x << ", " << pos.y << ")\n";
                break;
            default: {
                static const std::map<GateType, std::string> typeNames = {
                    {GateType::AND, "AND"},
                    {GateType::OR, "OR"},
                    {GateType::NOT, "NOT"},
                    {GateType::XOR, "XOR"},
                    {GateType::NAND, "NAND"},
                    {GateType::NOR, "NOR"},
                    {GateType::XNOR, "XNOR"},
                    {GateType::CLOCK, "CLOCK"},
                    {GateType::POWER, "POWER"},
                    {GateType::SWITCH, "SWITCH"},
                    {GateType::BUTTON, "BUTTON"},
                    {GateType::LED, "LED"},
                    {GateType::ROM, "ROM"},
                    {GateType::SEG7, "7SEG"},
                    {GateType::LCD, "LCD"},
                    {GateType::COUNTER, "COUNTER"},
                    {GateType::REGISTER, "REGISTER"}
                };
                auto typeIt = typeNames.find(gate->getType());
                std::string typeName = typeIt != typeNames.end() ? typeIt->second : "UNKNOWN";
                out << "  gate " << typeName << " " << id << " at (" << pos.x << ", " << pos.y << ")\n";
                break;
            }
        }
    }

    out << "\n  // Connections\n";
    for (const auto& wire : wires) {
        auto fromIt = gateIds.find(wire.fromPin->parent);
        auto toIt = gateIds.find(wire.toPin->parent);
        if (fromIt == gateIds.end() || toIt == gateIds.end()) continue;
        int fromPinIdx = -1, toPinIdx = -1;
        for (size_t i = 0; i < wire.fromPin->parent->outputs.size(); i++) {
            if (&wire.fromPin->parent->outputs[i] == wire.fromPin) {
                fromPinIdx = static_cast<int>(i);
                break;
            }
        }
        for (size_t i = 0; i < wire.toPin->parent->inputs.size(); i++) {
            if (&wire.toPin->parent->inputs[i] == wire.toPin) {
                toPinIdx = static_cast<int>(i);
                break;
            }
        }
        if (fromPinIdx >= 0 && toPinIdx >= 0) {
            out << "  wire " << fromIt->second << "." << fromPinIdx << " -> " << toIt->second << "." << toPinIdx << "\n";
        }
    }
    out << "\n}\n";
    return out.str();
}

